// Run with `node scripts/extract-snippets.mjs` (see package.json).
/**
 * extract-snippets: pull the `#region`-marked blocks out of the type-checked example files into
 *   - `examples/snippets.json`, which the docs render by id, and
 *   - `src/generated/example-snippets.ts`, which the CLI's `add <framework>` recipes are built from,
 * so every snippet a user sees, on the site or from the CLI, is real, compiled code from the current
 * library: an example that stops compiling fails CI before it can be published stale.
 *
 * Markers (matching TypeDoc/VS Code region syntax):
 *   // #region <id>
 *   ...code...
 *   // #endregion <id>
 *
 * `--check` verifies both outputs are in sync with the sources (CI gate) instead of writing them.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const EXAMPLES_DIR = resolve(__dirname, '../examples')
const OUT = join(EXAMPLES_DIR, 'snippets.json')
const OUT_TS = resolve(__dirname, '../src/generated/example-snippets.ts')

const REGION = /\/\/\s*#region\s+(\S+)\s*\n([\s\S]*?)\n\s*\/\/\s*#endregion(?:\s+\S+)?/g

/** Collect .ts files at the top level and one level down (e.g. examples/frameworks/). */
function tsFiles() {
  /** @type {string[]} */
  const out = []
  for (const entry of readdirSync(EXAMPLES_DIR, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.ts')) {
      out.push(join(EXAMPLES_DIR, entry.name))
    } else if (entry.isDirectory()) {
      const sub = join(EXAMPLES_DIR, entry.name)
      for (const f of readdirSync(sub).filter((f) => f.endsWith('.ts'))) out.push(join(sub, f))
    }
  }
  return out
}

/** @returns {Record<string,string>} */
function extract() {
  /** @type {Record<string,string>} */
  const snippets = {}
  for (const file of tsFiles()) {
    // Normalise CRLF so the output does not depend on the checkout's line endings.
    // Without this, regenerating on Windows embeds \r\n in every snippet string and the
    // `--check` gate then fails on Linux CI (and vice versa) with no real change.
    const src = readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
    let m
    while ((m = REGION.exec(src)) !== null) {
      const [, id, body] = m
      if (snippets[id]) throw new Error(`duplicate snippet id "${id}" (in ${file})`)
      // Trim a single trailing newline but keep internal blank lines / indentation.
      snippets[id] = body.replace(/\s+$/, '') + '\n'
    }
  }
  return snippets
}

const snippets = extract()
const ids = Object.keys(snippets)
if (ids.length === 0) {
  console.error('[extract-snippets] no #region snippets found under examples/')
  process.exit(1)
}
const serialized = JSON.stringify(snippets, null, 2) + '\n'
const serializedTs =
  '// GENERATED by scripts/extract-snippets.mjs from the type-checked files under examples/.\n' +
  '// Do not edit: change the example, then run `npm run snippets`.\n\n' +
  '/** Each `#region` block of the examples, by id: compiled code, not hand-typed strings. */\n' +
  `export const EXAMPLE_SNIPPETS: Readonly<Record<string, string>> = ${JSON.stringify(snippets, null, 2)};\n`

/** Read a file for comparison with CRLF normalised, so the gate is line-ending neutral. */
const current = (path) => (existsSync(path) ? readFileSync(path, 'utf8').replace(/\r\n/g, '\n') : '')

if (process.argv.includes('--check')) {
  const stale = [
    [OUT, serialized, 'examples/snippets.json'],
    [OUT_TS, serializedTs, 'src/generated/example-snippets.ts'],
  ].filter(([path, expected]) => current(path) !== expected)
  if (stale.length > 0) {
    console.error(`[extract-snippets] DRIFT: ${stale.map(([, , name]) => name).join(', ')} stale. Run \`npm run snippets\` and commit.`)
    process.exit(1)
  }
  console.log(`[extract-snippets] snippets.json and example-snippets.ts in sync (${ids.length}: ${ids.join(', ')}) ✓`)
} else {
  mkdirSync(dirname(OUT_TS), { recursive: true })
  writeFileSync(OUT, serialized)
  writeFileSync(OUT_TS, serializedTs)
  console.log(`[extract-snippets] wrote ${ids.length} snippet(s) → examples/snippets.json, src/generated/example-snippets.ts`)
}
